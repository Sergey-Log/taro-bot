def format_reading(cards, positions=None):
    if positions is None:
        positions = ["🎴 Прошлое", "🎴 Настоящее", "🎴 Будущее"]
    
    result = "🔮 ВАШ РАСКЛАД ТАРО ГОТОВ 🔮\n\n"
    
    for pos, (name, meaning) in zip(positions, cards):
        result += f"{pos}\n"
        result += f"✨ {name}\n"
        result += f"💫 {meaning}\n\n"
    
    result += "🌙 Помните: карты показывают возможности, а выбор всегда за вами!"
    return result
def get_random_cards(count=3):
    """
    Получить случайные карты для расклада
    
    Args:
        count: количество карт (по умолчанию 3)
        
    Returns:
        список кортежей (название, интерпретация)
    """
    cards = random.sample(list(MAJOR_ARCANA.keys()), count)
    return [(card, MAJOR_ARCANA[card]) for card in cards]

def format_reading(cards, positions=None):
    """
    Форматирование расклада в красивый текст с подробной интерпретацией
    
    Args:
        cards: список карт [(название, интерпретация), ...]
        positions: список позиций ["Прошлое", "Настоящее", ...]
        
    Returns:
        отформатированный текст расклада
    """
    if positions is None:
        positions = ["🎴 Прошлое", "🎴 Настоящее", "🎴 Будущее"]
    
    result = "🔮 ВАШ РАСКЛАД ТАРО ГОТОВ 🔮\n"
    result += "━━━━━━━━━━━━━━━━━━━━\n\n"
    
    for pos, (name, interpretation) in zip(positions, cards):
        result += f"{pos}\n"
        result += f"━━━━━━━━━━━━━━━━━━━━\n"
        result += f"✨ Карта: {name}\n"
        result += f"💫 Значение: {interpretation['short']}\n\n"
        result += f"❤️‍🔥 В любви: {interpretation['love']}\n"
        result += f"💼 В карьере: {interpretation['career']}\n"
        result += f"🌟 Совет: {interpretation['advice']}\n\n"
    
    result += "━━━━━━━━━━━━━━━━━━━━\n"
    result += "🌙 Помните: карты показывают возможности, а выбор всегда за вами!\n"
    result += "💫 Хотите увидеть историю своих раскладов? Напишите /history"
    
    return result

def get_single_card():
    """Получить одну случайную карту (для карты дня)"""
    card_name = random.choice(list(MAJOR_ARCANA.keys()))
    return (card_name, MAJOR_ARCANA[card_name])